    /**
     * Export pure SVG diagram
     */
    fun exportToSvg(mindmap: Mindmap, nodes: List<MindNode>): String {
        if (nodes.isEmpty()) return "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"400\" height=\"200\"><text x=\"20\" y=\"40\">Empty Mindmap</text></svg>"

        val nodeMap = nodes.associateBy { it.id }
        var minX = Float.MAX_VALUE
        var minY = Float.MAX_VALUE
        var maxX = Float.MIN_VALUE
        var maxY = Float.MIN_VALUE

        for (n in nodes) {
            minX = minOf(minX, n.posX)
            maxX = maxOf(maxX, n.posX + 200f)
            minY = minOf(minY, n.posY)
            maxY = maxOf(maxY, n.posY + 70f)
        }

        val padding = 60f
        val width = (maxX - minX + padding * 2).toInt()
        val height = (maxY - minY + padding * 2).toInt()
        val shiftX = -minX + padding
        val shiftY = -minY + padding

        val pathsBuilder = StringBuilder()
        for (n in nodes) {
            if (n.parentId.isNotBlank() && nodeMap.containsKey(n.parentId)) {
                val p = nodeMap[n.parentId]!!
                val sx = p.posX + shiftX + 90f
                val sy = p.posY + shiftY + 25f
                val ex = n.posX + shiftX + 90f
                val ey = n.posY + shiftY + 25f
                val cx = sx + (ex - sx) / 2
                pathsBuilder.append(
                    "<path d=\"M $sx $sy C $cx $sy, $cx $ey, $ex $ey\" fill=\"none\" stroke=\"${p.colorHex}\" stroke-width=\"2.5\" opacity=\"0.7\" />\n"
                )
            }
        }

        val nodesBuilder = StringBuilder()
        for (n in nodes) {
            val x = n.posX + shiftX
            val y = n.posY + shiftY
            val safeTitle = n.title.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            nodesBuilder.append(
                """
  <g transform="translate($x, $y)">
    <rect width="180" height="50" rx="12" fill="#161B22" stroke="${n.colorHex}" stroke-width="2" />
    <text x="14" y="30" fill="#E6EDF3" font-family="system-ui, sans-serif" font-size="13" font-weight="bold">${n.icon} $safeTitle</text>
  </g>
                """.trimIndent()
            ).append("\n")
        }

        return """
<svg xmlns="http://www.w3.org/2000/svg" width="$width" height="$height" viewBox="0 0 $width $height">
  <rect width="100%" height="100%" fill="#0D1117" />
  <text x="30" y="40" fill="#58A6FF" font-family="system-ui, sans-serif" font-size="20" font-weight="bold">${mindmap.title}</text>
  <text x="30" y="60" fill="#8B949E" font-family="system-ui, sans-serif" font-size="12">Subject: ${mindmap.subject} • MindNexus Export</text>
  
  $pathsBuilder
  $nodesBuilder
</svg>
        """.trimIndent()
    }

    /**
     * Export hierarchical Markdown outline
     */
    fun exportToMarkdown(mindmap: Mindmap, nodes: List<MindNode>): String {
        val sb = StringBuilder()
        sb.append("# ${mindmap.title}\n\n")
        sb.append("> **Subject:** ${mindmap.subject} | **Nodes:** ${nodes.size}\n")
        if (mindmap.description.isNotBlank()) {
            sb.append("> ${mindmap.description}\n")
        }
        sb.append("\n---\n\n")

        val roots = nodes.filter { it.parentId.isBlank() || nodes.none { p -> p.id == it.parentId } }
        val childrenMap = nodes.groupBy { it.parentId }

        fun appendBranch(node: MindNode, level: Int) {
            val indent = "  ".repeat(level)
            val badge = if (node.mastery == "MASTERED") "[✓]" else "[ ]"
            sb.append("$indent- $badge **${node.icon} ${node.title}**\n")
            if (node.notesMarkdown.isNotBlank()) {
                val noteLines = node.notesMarkdown.lines()
                for (line in noteLines) {
                    sb.append("$indent    $line\n")
                }
            }
            val children = childrenMap[node.id] ?: emptyList()
            for (child in children) {
                appendBranch(child, level + 1)
            }
        }

        for (root in roots) {
            appendBranch(root, 0)
        }

        return sb.toString()
    }

    /**
     * Export complete JSON format for backup & cloud restore
     */
    fun exportToJson(mindmap: Mindmap, nodes: List<MindNode>): String {
        val root = JSONObject().apply {
            put("version", "1.0")
            put("exportedAt", SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss'Z'", Locale.US).format(Date()))
            put("mindmap", JSONObject().apply {
                put("id", mindmap.id)
                put("title", mindmap.title)
                put("description", mindmap.description)
                put("theme", mindmap.theme)
                put("subject", mindmap.subject)
                put("tags", JSONArray(mindmap.tags))
                put("layoutType", mindmap.layoutType)
            })
            put("nodes", JSONArray().apply {
                for (n in nodes) {
                    put(JSONObject().apply {
                        put("id", n.id)
                        put("parentId", n.parentId)
                        put("title", n.title)
                        put("notesMarkdown", n.notesMarkdown)
                        put("posX", n.posX.toDouble())
                        put("posY", n.posY.toDouble())
                        put("colorHex", n.colorHex)
                        put("shape", n.shape)
                        put("icon", n.icon)
                        put("mastery", n.mastery)
                        put("dueDate", n.dueDate)
                        put("priority", n.priority)
                        put("tags", JSONArray(n.tags))
                        put("attachments", JSONArray(n.attachments))
                        put("crossLinks", JSONArray(n.crossLinks))
                    })
                }
            })
        }
        return root.toString(2)
    }

    /**
     * Import JSON data back into mindmap and nodes
     */
    fun importFromJson(jsonString: String, targetUserId: String): Pair<Mindmap, List<MindNode>> {
        val obj = JSONObject(jsonString)
        val mObj = obj.getJSONObject("mindmap")
        val mindmapId = mObj.optString("id", "imported_${System.currentTimeMillis()}")
        val mindmap = Mindmap(
            id = mindmapId,
            userId = targetUserId,
            title = mObj.optString("title", "Imported Mindmap"),
            description = mObj.optString("description", ""),
            theme = mObj.optString("theme", "OBSIDIAN"),
            subject = mObj.optString("subject", "General"),
            layoutType = mObj.optString("layoutType", "TREE")
        )

        val nodesList = mutableListOf<MindNode>()
        val nArr = obj.optJSONArray("nodes")
        if (nArr != null) {
            for (i in 0 until nArr.length()) {
                val n = nArr.getJSONObject(i)
                nodesList.add(
                    MindNode(
                        id = n.optString("id", "n_$i"),
                        mindmapId = mindmapId,
                        userId = targetUserId,
                        parentId = n.optString("parentId", ""),
                        title = n.optString("title", "Node"),
                        notesMarkdown = n.optString("notesMarkdown", ""),
                        posX = n.optDouble("posX", 0.0).toFloat(),
                        posY = n.optDouble("posY", 0.0).toFloat(),
                        colorHex = n.optString("colorHex", "#58A6FF"),
                        shape = n.optString("shape", "ROUNDED"),
                        icon = n.optString("icon", "💡"),
                        mastery = n.optString("mastery", "UNLEARNED"),
                        dueDate = n.optString("dueDate", ""),
                        priority = n.optString("priority", "MEDIUM")
                    )
                )
            }
        }
        return Pair(mindmap, nodesList)
    }
